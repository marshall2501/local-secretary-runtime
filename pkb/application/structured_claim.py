"""PKB structured claim write, without a second natural-language interpreter.

RITSUKO supplies a persisted Task/operation identity and user-authored text.
The authoritative PKB repository independently enforces evidence grounding,
entity aliases, conflicts, authorization and idempotency at commit time.
This application entry does not choose a Tool or grant permission to write.
"""
from __future__ import annotations

from dataclasses import asdict
from datetime import datetime
from uuid import UUID, NAMESPACE_URL, uuid5

from pkb.ingestion_gate import InputRecord, ProposedClaim
from pkb.write_service import KNOWN_PREDICATES


def register_structured_claim(
    repository,
    *,
    task_id: str,
    invocation_id: str,
    user_text: str,
    entity_id: str,
    entity_mention: str,
    predicate: str,
    value: str,
    evidence_start: int,
    evidence_end: int,
    recorded_at: datetime,
    occurred_at: datetime,
) -> dict:
    """Write an explicitly user-grounded, single PKB claim via existing PKB rules.

    Both IDs must be issued by RITSUKO, not generated by MAGI. The stable
    recorded/occurred times must come from the persisted Task input; using the
    current clock here would defeat PKB receipt replay checks on a retry.

    This first slice supports the same explicit event predicates as the
    existing single-claim PKB writer. Entity creation, relationships, quantity,
    corrections and unsupported attributes are intentionally not inferred.
    """
    try:
        task_uuid = UUID(task_id)
        invocation_uuid = UUID(invocation_id)
        entity_uuid = UUID(entity_id)
    except (ValueError, TypeError, AttributeError) as exc:
        raise ValueError("invalid_structured_claim_identity") from exc

    if (type(user_text) is not str or not user_text.strip()
            or len(user_text) > 20000):
        raise ValueError("invalid_original_text")
    if (type(entity_mention) is not str or not entity_mention.strip()
            or type(predicate) is not str or predicate not in KNOWN_PREDICATES
            or type(value) is not str or not value.strip()):
        raise ValueError("unsupported_structured_claim")
    if (type(evidence_start) is not int or type(evidence_end) is not int
            or not 0 <= evidence_start < evidence_end <= len(user_text)):
        raise ValueError("invalid_structured_claim_evidence")
    quote = user_text[evidence_start:evidence_end]
    if entity_mention not in quote or value not in quote:
        raise ValueError("structured_claim_not_grounded_in_user_text")
    if (not isinstance(recorded_at, datetime)
            or not isinstance(occurred_at, datetime)
            or recorded_at.utcoffset() is None
            or occurred_at.utcoffset() is None):
        raise ValueError("structured_claim_times_must_be_persisted_and_aware")

    # The same Task operation always receives the same receipt identity.
    # A different payload against this identity is rejected by PKB's
    # transactional payload-hash check rather than committed twice.
    input_id = str(uuid5(
        NAMESPACE_URL,
        f"local-secretary:pkb-claim:{task_uuid}:{invocation_uuid}",
    ))
    record = InputRecord(
        input_id=input_id,
        source_kind="user_statement",
        source_ref=repository.source_ref("ritsuko-task", input_id),
        text=user_text,
        recorded_at=recorded_at,
        occurred_at=occurred_at,
        confidentiality="private",
    )
    claim = ProposedClaim(
        entity_key=str(entity_uuid),
        entity_mention=entity_mention,
        predicate=predicate,
        value=value,
        evidence_start=evidence_start,
        evidence_end=evidence_end,
        evidence_quote=quote,
    )
    return asdict(repository.write_one(record, claim))
